const exactReplacements = new Map(replacements);
const cjkRe = /[\u4e00-\u9fff]/;
const normalizeWhitespace = (value: string) => value.replace(/\s+/g, ' ').trim();
const normalizedExactReplacements = new Map(
  replacements.map(([source, target]) => [normalizeWhitespace(source), target]),
);
const placeholderRe = /\{[^{}]*\}/g;
const escapeRegExp = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const dynamicReplacements = replacements
  .filter(([source]) => /\{[^{}]*\}/.test(source))
  .sort((a, b) => b[0].length - a[0].length)
  .map(([source, target]) => {
    placeholderRe.lastIndex = 0;
    const parts = normalizeWhitespace(source).split(placeholderRe).map(escapeRegExp);
    placeholderRe.lastIndex = 0;
    return { pattern: new RegExp(`^${parts.join('(.*?)')}$`, 'u'), target };
  });
const partialReplacements = sortedReplacements.filter(([source]) => (
  cjkRe.test(source) || /[（）：「」【】、，。；]/.test(source)
));
export function translateRu(value: string): string {
  if (!value) {
    return value;
  }
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const core = value.trim();
  const exact = exactReplacements.get(core);
  if (exact) {
    return `${leading}${exact}${trailing}`;
  }
  const normalizedExact = normalizedExactReplacements.get(normalizeWhitespace(core));
  if (normalizedExact) {
    return `${leading}${normalizedExact}${trailing}`;
  }
  const normalizedCore = normalizeWhitespace(core);
  for (const replacement of dynamicReplacements) {
    const match = replacement.pattern.exec(normalizedCore);
    if (!match) continue;
    let capture = 1;
    const translated = replacement.target.replace(placeholderRe, () => match[capture++] ?? '');
    return `${leading}${translated}${trailing}`;
  }
  if (!cjkRe.test(value)) {
    return value;
  }

  let out = value;
  for (const [source, target] of partialReplacements) {
    if (out.includes(source)) {
      out = out.split(source).join(target);
    }
  }
  out = out
    .replace(/(\d+)\s*天后重置/g, '$1 дн до сброса')
    .replace(/(\d+)\s*小时(\d+)\s*分钟后重置/g, '$1 ч $2 мин до сброса')
    .replace(/(\d+)\s*分钟后重置/g, '$1 мин до сброса')
    .replace(/(\d+)\s*天\s*(\d+)\s*小时\s*(\d+)\s*分钟\s*后重置/g, '$1 дн $2 ч $3 мин до сброса')
    .replace(/(\d+)\s*小时\s*(\d+)\s*分钟\s*(\d+)\s*秒\s*后重置/g, '$1 ч $2 мин $3 с до сброса')
    .replace(/(\d+)\s*分钟\s*(\d+)\s*秒\s*后重置/g, '$1 мин $2 с до сброса')
    .replace(/(\d+)\s*秒\s*后重置/g, '$1 с до сброса')
    .replace(/(\d+)\s*天到期/g, '$1 дн до окончания')
    .replace(/(\d+)\s*天前/g, '$1 дн назад')
    .replace(/(\d+)\s*小时前/g, '$1 ч назад')
    .replace(/(\d+)\s*分钟前/g, '$1 мин назад')
    .replace(/(\d+)\s*个使用额度/g, '$1 кредитов использования')
    .replace(/(\d+)\s*个工作区额度/g, '$1 кредитов workspace')
    .replace(/(\d+)\s*次限额重置/g, '$1 сбросов лимита')
    .replace(/(\d+)\s*个账号/g, '$1 аккаунтов')
    .replace(/(\d+)\s*人/g, '$1 чел.')
    .replace(/(\d+)\s*条/g, '$1 зап.')
    .replace(/(\d+)\s*小\s*ч/g, '$1 ч')
    .replace(/(\d+)\s*天/g, '$1 дн')
    .replace(/(\d+)\s*小时/g, '$1 ч')
    .replace(/(\d+)\s*分钟/g, '$1 мин')
    .replace(/(\d+)\s*秒/g, '$1 с')
    .replace(/(\d+)\s*时/g, '$1 ч')
    .replace(/(\d+)\s*分/g, '$1 мин')
    .replace(/(\d+)\s*ч/g, '$1 ч')
    .replace(/(\d+)\s*мин/g, '$1 мин')
    .replace(/(\d+)\s*с\b/g, '$1 с');
  return out;
}

