const translateMessage = createTranslator(englishReplacements);
export function translateEn(value: string): string {
  const countdown = value.trim().match(/^((?:\d+\s*(?:天|小时|分钟|秒|时|分)\s*)+)后重置$/);
  if (countdown) {
    const units: Record<string, string> = { 天: 'd', 小时: 'h', 分钟: 'm', 秒: 's', 时: 'h', 分: 'm' };
    const duration = [...countdown[1].matchAll(/(\d+)\s*(天|小时|分钟|秒|时|分)/g)]
      .map((part) => part[1] + units[part[2]]).join(' ');
    return duration + ' until reset';
  }
  return translateMessage(value);
}
